GLOSSARY = [
    dict(term="Agent", definition="The learner/controller that picks actions."),
    dict(term="Environment", definition="The world the agent interacts with; returns new states and rewards."),
    dict(term="State / Observation", definition="What the agent perceives. States are the true world; observations may hide parts of it."),
    dict(term="Action space", definition="Set of allowed actions - discrete (pick one) or continuous (real-valued vectors)."),
    dict(term="Reward", definition="Scalar feedback signal the agent maximises over time."),
    dict(term="Episode", definition="One full run from reset to termination/truncation."),
    dict(term="Policy π(a|s)", definition="The agent's decision rule mapping states to actions."),
    dict(term="Value function V(s)", definition="Expected total future reward from state s under the policy."),
    dict(term="Q-function Q(s,a)", definition="Expected total reward from taking action a in s, then following the policy."),
    dict(term="Discount factor γ", definition="0..1 weight of future vs immediate reward. Low γ = myopic, high γ = far-sighted."),
    dict(term="Exploration vs exploitation", definition="Trying new actions to gain information vs using known-good actions to score."),
    dict(term="ε-greedy", definition="Explore with probability ε, otherwise act greedily on current values."),
    dict(term="On-policy / Off-policy", definition="Whether the method learns about the same policy it collects data with (on) or a different/target one (off)."),
    dict(term="Replay buffer", definition="Memory of past transitions sampled randomly for off-policy learning."),
    dict(term="Target network", definition="Slowly-updated copy of the network providing stable learning targets."),
    dict(term="Advantage A(s,a)", definition="How much better action a was than expected: A = Q − V. Reduces gradient variance."),
    dict(term="GAE", definition="Generalised Advantage Estimation - exponentially-weighted mix of TD residuals (λ parameter)."),
    dict(term="Entropy bonus", definition="Loss term rewarding policy randomness so agents keep exploring."),
    dict(term="Checkpoint", definition="Saved snapshot of model weights (and often optimiser state) during training."),
    dict(term="Seed", definition="Random-number starting point; identical seeds should reproduce identical runs."),
    dict(term="mean100", definition="Average episode reward over the last 100 episodes - the smooth 'training health' curve."),
    {"term": 'Bootstrapping', "definition": "Updating an estimate from another estimate: a TD target uses the current guess of the next state's value instead of waiting for the true return."},
    {"term": 'TD error', "definition": 'The gap between a value estimate and its one-step target, δ = r + γ V(s′) − V(s). Most value-based methods shrink it; a TD error that never falls signals a bug or too high a learning rate.'},
    {"term": 'Prioritised replay', "definition": 'Sampling transitions in proportion to their last TD error, so surprising experience is replayed more often.', "algorithm": 'dqn_per'},
    {"term": 'Return', "definition": 'The (discounted) sum of rewards from a time step to the end of the episode. What the agent is trying to maximise.'},
    {"term": 'Policy gradient', "definition": 'Methods that adjust policy parameters directly in the direction that makes high-return actions more likely.', "algorithm": 'reinforce'},
    {"term": 'Actor-critic', "definition": 'A policy (actor) trained with help from a learned value function (critic) that judges its actions.', "algorithm": 'a2c'},
    {"term": 'Model-based RL', "definition": 'Methods that learn how the environment works and use that model to plan or to generate extra experience.', "algorithm": 'dyna_q'},
    {"term": 'Distributional RL', "definition": 'Learning the full distribution of returns instead of only its mean.', "algorithm": 'c51'},
    {"term": 'Upper confidence bound', "definition": 'Exploration by optimism: add a bonus that is large for rarely tried actions and shrinks with experience.', "algorithm": 'ucb'},
    {"term": 'Sparse reward', "definition": 'A task where almost every step gives zero reward, so the learner gets little signal until it stumbles on success.'},
    {"term": 'Action mask', "definition": 'A list of which actions are legal right now. Mask-aware algorithms never choose an illegal move.'},
    {"term": 'Overestimation bias', "definition": 'Taking the maximum over noisy value estimates systematically picks lucky ones, inflating values. Double Q-learning and Double DQN reduce it.', "algorithm": 'dqn_double'},
    {"term": 'Diagnostic probe', "definition": 'A tiny environment with a known answer that a correct implementation must solve in seconds.'},
]

